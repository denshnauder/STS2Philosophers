            (PhilosophersGazePage.ZHUANGZI_INTRO, PhilosophersGazeOption.ZhuangziRope) => Navigate(PhilosophersGazePage.ZHUANGZI_RESULT_ROPE),
            (PhilosophersGazePage.YANGZHU_INTRO, PhilosophersGazeOption.YangzhuOutside) => Navigate(PhilosophersGazePage.YANGZHU_RESULT_OUTSIDE),
            (PhilosophersGazePage.YANGZHU_INTRO, PhilosophersGazeOption.YangzhuInside) => Navigate(PhilosophersGazePage.YANGZHU_RESULT_INSIDE),
            (PhilosophersGazePage.HUISHI_RESULT_BAMBOO, PhilosophersGazeOption.Again) => Navigate(PhilosophersGazePage.HUISHI_RESULT_FIST),
            (PhilosophersGazePage.HUISHI_RESULT_BAMBOO, PhilosophersGazeOption.Stop) => Navigate(PhilosophersGazePage.HUISHI_RESULT_HAND),
            (PhilosophersGazePage.HUISHI_RESULT_EAR, PhilosophersGazeOption.Again) => Navigate(PhilosophersGazePage.HUISHI_RESULT_FIST),
            (PhilosophersGazePage.HUISHI_RESULT_EAR, PhilosophersGazeOption.Stop) => Navigate(PhilosophersGazePage.HUISHI_RESULT_HAND),
            (PhilosophersGazePage.QIN_RESULT_PUSH, PhilosophersGazeOption.Accept) => Finish(PhilosophersGazePage.QinGuliShouChengXie, PhilosophersGazeEffect.ReplaceWithQinGuliShouChengXie),
            (PhilosophersGazePage.QIN_RESULT_PUSH, PhilosophersGazeOption.Decline) => Finish(PhilosophersGazePage.QinGuliDecline, PhilosophersGazeEffect.RecordContinuationDecline),
            (PhilosophersGazePage.QIN_RESULT_MAP, PhilosophersGazeOption.Accept) => Finish(PhilosophersGazePage.QinGuliShouChengXie, PhilosophersGazeEffect.ReplaceWithQinGuliShouChengXie),
            (PhilosophersGazePage.QIN_RESULT_MAP, PhilosophersGazeOption.Decline) => Finish(PhilosophersGazePage.QinGuliDecline, PhilosophersGazeEffect.RecordContinuationDecline),
            (PhilosophersGazePage.ZHUANGZI_RESULT_LIFT, PhilosophersGazeOption.ZhuangziBorrow) => Navigate(PhilosophersGazePage.ZHUANGZI_RESULT_BORROW),
            (PhilosophersGazePage.ZHUANGZI_RESULT_LIFT, PhilosophersGazeOption.ZhuangziWalk) => Navigate(PhilosophersGazePage.ZHUANGZI_RESULT_WALK),
            (PhilosophersGazePage.ZHUANGZI_RESULT_ROPE, PhilosophersGazeOption.ZhuangziBorrow) => Navigate(PhilosophersGazePage.ZHUANGZI_RESULT_BORROW),
            (PhilosophersGazePage.ZHUANGZI_RESULT_ROPE, PhilosophersGazeOption.ZhuangziWalk) => Navigate(PhilosophersGazePage.ZHUANGZI_RESULT_WALK),
            (PhilosophersGazePage.YANGZHU_RESULT_OUTSIDE, PhilosophersGazeOption.YangzhuTake) => Navigate(PhilosophersGazePage.YANGZHU_RESULT_TAKE),
            (PhilosophersGazePage.YANGZHU_RESULT_OUTSIDE, PhilosophersGazeOption.YangzhuCoil) => Navigate(PhilosophersGazePage.YANGZHU_RESULT_COIL),
            (PhilosophersGazePage.YANGZHU_RESULT_INSIDE, PhilosophersGazeOption.YangzhuTake) => Navigate(PhilosophersGazePage.YANGZHU_RESULT_TAKE),
            (PhilosophersGazePage.YANGZHU_RESULT_INSIDE, PhilosophersGazeOption.YangzhuCoil) => Navigate(PhilosophersGazePage.YANGZHU_RESULT_COIL),
            (PhilosophersGazePage.HUISHI_RESULT_FIST, PhilosophersGazeOption.Accept) => Finish(PhilosophersGazePage.HuishiLiWuChou, PhilosophersGazeEffect.ReplaceWithHuishiLiWuChou),
            (PhilosophersGazePage.HUISHI_RESULT_HAND, PhilosophersGazeOption.Decline) => Finish(PhilosophersGazePage.HuishiDecline, PhilosophersGazeEffect.RecordContinuationDecline),
            (PhilosophersGazePage.ZHUANGZI_RESULT_BORROW, PhilosophersGazeOption.Accept) => Finish(PhilosophersGazePage.ZhuangziDaHu, PhilosophersGazeEffect.ReplaceWithZhuangziDaHu),
            (PhilosophersGazePage.ZHUANGZI_RESULT_WALK, PhilosophersGazeOption.Decline) => Finish(PhilosophersGazePage.ZhuangziDecline, PhilosophersGazeEffect.RecordContinuationDecline),
            (PhilosophersGazePage.YANGZHU_RESULT_TAKE, PhilosophersGazeOption.Accept) => Finish(PhilosophersGazePage.YangzhuQuanShengBi, PhilosophersGazeEffect.ReplaceWithYangzhuQuanShengBi),
            (PhilosophersGazePage.YANGZHU_RESULT_COIL, PhilosophersGazeOption.Decline) => Finish(PhilosophersGazePage.YangzhuDecline, PhilosophersGazeEffect.RecordContinuationDecline),
            _ => default,
        };
        return transition != default;
    }

