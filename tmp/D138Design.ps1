# 第欧根尼问题事件角色定位

## D138为什么不再强求主能力

既定18把第欧根尼列为“实践”，可作问号与内批；样例路径中他是第二幕问号，19又要求他能形成公开自足的合法终点，不能只当芝诺钥匙。这不等于他必须发一件战斗遗物或成为新的数值主说。

D130—D136已经证明，为了把他塞进主要能力而寻找药水限制、额外攻击牌、随机遗物或可暂停赐福，会重复普通战术、依赖上游偶然状态，或变成被动困难模式。D138改为先确定人物在共同框架里的职责：**第欧根尼是会留下路线事实的实践型Question；只有玩家后来选择芝诺时才发生主说替换。**

## 三种角色结构比较

| 结构 | 单一主说 | 玩家实际代价 | 第欧根尼终点 | 问题 |
| --- | --- | --- | --- | --- |
| 第二幕直接Adopt第欧根尼战斗赐福 | 可保持单一，但必须删除旧赐福 | 取决于新能力平衡 | 可作为当前主说停留 | 至今候选均不成立，容易再造牌序/数值 |
| 第二幕Adopt无战斗效果的第欧根尼状态 | 形式上单一 | 立即失去旧赐福，成为困难模式 | 身份清楚 | D135/D136已否决为主要循环 |
| 第二幕Question/Practice保留旧主说，第三幕Stay或Switch | 始终只有旧主说或芝诺一个生效 | 停留会放弃第三幕新主说机会；公开说法会改变后继内容 | 路线以第欧根尼问题结束，旧主说只是仍在生效的早先实践 | 需要把“路线最后问题”和“当前机械主说”明确分开 |

采用第三种作为设计方向。它复用普罗泰戈拉等Question/Keep已有概念：一个人物可以实质挑战当前路线、保存事实并改变后继，而不自动发第二套能力。这里的“停留第欧根尼”表示玩家把公开自足问题作为本局哲学终点，不表示历史第欧根尼授予一件遗物，也不把先前主说改名为犬儒能力。

## 正式节点、操作、界面和素材

### 第二幕Question/Practice

- 出现：按既定候选条件进入第欧根尼Question，不另加地图节点。
- 操作：看见一个由实际路线事实构成的公开问题；玩家可作出说法、拒绝作答或指出没有足够材料。所有选择保留当前机械主说。
- 结果：保存第欧根尼问题记录、接收者已知事实和玩家明确说法；不发遗物、牌、金币、生命或隐藏分。
- 界面：标准事件人物页、选择页、结果页；复用路线历史查看，不开战斗浮层。
- 素材：一张第欧根尼静态图。没有群众、桶屋、街市或身体动作动画。

### 两节点之间

不新增被动监控普通最优战术。只有当前主说或既有路线已经记录、且与公开说法直接相关的事实，才能进入后继材料。无兼容事实记“无材料”，不把未触发、没遇到或调试跳过写成坚持。

### 第三幕后继或终点

- Stay：回看第二幕说法和后来实际材料，可保持、修订、撤回或拒绝总结；关闭本局后续哲学主说切换，但当前机械主说仍是此前唯一主说。
- Switch Zeno：页面向芝诺陈述同一组可知事实，明确犬儒传统经克拉特斯等进入早期斯多亚；确认后才由芝诺正常替换此前主说。
- 无论Stay或Switch，第二幕拒答都不是失败；第三幕可以首次说明，也可以继续不作自我认证。
- 界面：标准事件/结果页；第欧根尼和芝诺各一张静态图。克拉特斯只在中介说明卡出现，不作为无素材说话角色。

## 完整决策循环的最低形态

这个角色方向要求未来内容至少有两次玩家动作：

1. 第二幕面对第欧根尼和一项本局真实事实，决定公开什么、保留什么或为何暂不下判断；
2. 第三幕面对路线终点或芝诺，看到事实是否变化，再保持、修订、撤回或转向。

循环的核心收益是路线与关系发生变化，不是战斗数值。其代价是公开说法不可假装未曾说出，以及Stay放弃新的主说替换机会。玩家后来修订理由不会删除先前接收者已经知道的内容；程序记录知识流，不评分“诚实值”。

## 与自足、操练和直言的对应边界

- 操练：两次公开行动之间有真实时间和事实变化；但若中间没有兼容材料，就只能称问题链，不能称已完成操练。
- 自足：必须由具体内容说明玩家较少依赖哪一种评价/惯例，以及替代如何实行。D138只定角色结构，未提供这项内容。
- 直言：有第欧根尼与芝诺两个明确接收者，且说法改变Stay/Switch关系；仍不是面对政治权势的完整parrhēsia。

因此角色定位通过不等于人物设计完成。它只取消“每个人物必须有战斗buff”的错误前提。

## 失败、恢复与反例

- 没有兼容前史：显示无材料并允许拒绝/离开，不编造玩家做过的事，不自动生成泛泛自足台词。
- 说法后来被事实推翻：允许修订，保留旧说和接收者知识，不扣资源。
- 第二幕拒答、第三幕开口：合法；不能把首次沉默锁成永久无资格。
- 第二幕公开、第三幕撤回：撤回当前主张，不删除已公开事实。
- 选择Stay只为保留旧强力赐福：程序不能判定动机；设计需承认这是可能策略，不把Stay自动写成犬儒德性。
- 选择Zeno只为新能力：同样不能判定动机；路线文本只说明玩家接受了另一种训练。

## D138判决

**批准“实践型Question/Keep + 第三幕Stay/Switch”作为第欧根尼的角色架构设计方向，未批准具体事件内容或生产。** 它遵守单一主说、合法终点和克拉特斯中介，避免硬造雷同战斗能力；需要的正式素材和界面也可明确预算。

准确下一步设计两次公开行动使用的同一具体事实。优先从当前西哲路线已经可靠保存的事实中选择，至少覆盖一种苏格拉底前史和一种柏拉图前史；不同前史可以有不同问题文本，但必须共享“谁知道什么、后来如何修订”的状态结构。若事实只证明普通最优战术或需要新增群众场景，否决。
