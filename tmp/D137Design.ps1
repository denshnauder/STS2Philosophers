## 保留的关系骨架

最低可承担结构只包含两个正式哲学节点：

1. 第二幕Question：第欧根尼接收一个玩家明确作出的说法；选项必须显示后续可修订，不把更强硬的话当正确答案。
2. 中段普通游戏：未来核心若成立，只记录与该说法直接相关的实际行动、无机会和修订；这里尚无批准材料。
3. 第三幕：若停留，第欧根尼路线形成有代价的合法实践终点；若转向芝诺，页面向芝诺陈述实际发生的事实，并用说明卡公开“犬儒传统经克拉特斯等进入早期斯多亚”，不画成第欧根尼亲授芝诺。
4. 两条结果都合法。程序不按“坚持次数”判断谁更犬儒；承认依赖也可以成为转向的真实理由。

正式界面只用标准事件选项、结果页和路线历史。素材预算为第欧根尼与芝诺各一张可读静态图；若克拉特斯成为说话角色则必须另计一张，当前不让他发言。无群众、街市、桶屋、王者或旅人场景，无战斗按钮和动画。静态图来源/风格仍未解决，不能因页数少写成制作已通过。

## 关系层能做什么、不能做什么

它能保证：

- 至少一个具体对象听见初始说法，另一个后继对象接收局内事实；
- 玩家说法会改变停留或切换主说，具有路线后果；
- 历史中介可公开，不伪造直接师承；
- 停留不是失败，转向也不是“未通过犬儒考试”。

它不能自动提供：

- 可反复选择的操练动作；
- 对外在需要的真实替代；
- 面对政治权势的强意义parrhēsia；
- 对动机、真实性或德性的程序判定。

## 标签与羞耻候选的边界

后续可以让第欧根尼质询玩家或他人给出的评价，但标签必须是本局事件实际出现的说法，不能把“犬”“圣人”“自足者”等身份直接授给玩家。可选动作是接受具体事实、修订评价、拒绝在证据不足时自称；三者都需有后续问题，不能让“谦虚答案”永远占优。

仅改变称号文本、忍受侮辱或选最冒犯的台词，没有实际行动与关系后果，均不成立。若为了制造公众必须新增传令者、群众或统治者，本轮停止，不用叙述假装素材已经存在。

