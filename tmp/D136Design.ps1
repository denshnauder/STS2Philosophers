**停止“放下当前主说机械赐福”作为第欧根尼主要能力、采用条件或通往芝诺的资格。** 它比随机遗物方案更诚实地指向现有帮助，却依赖上游恰好提供可逆持续效果；当前柏拉图核心候选并不满足。继续强行实现会让旧牌序赐福反过来绑架新设计，并把单一主说变成一显一隐两套规则。

本页保留为条件性表达机会：将来若某个具体主说天然有安全、玩家可见的临时拒绝时点，第欧根尼事件可以引用一次实际选择；该事实不能承担人物主循环、不能累计自足分，也不能自动解锁芝诺。

下一设计不再从“丢掉哪件东西/关闭哪个增益”出发。先比较现有事件关系中玩家能够对具体对象说什么、做什么，以及该表达如何改变停留或后继；优先关系与行动，不再寻找可牺牲资源。
