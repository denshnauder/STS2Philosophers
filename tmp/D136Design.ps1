### 对“触发时再问”的修补审查

可设想保留旧规则的影子计算：当旧赐福本应结算时，临时问玩家“接受并结束实践/拒绝本次帮助”。这会让帮助真实出现后再选择，修复无机会计数和战前盲猜，但代价不是小修：

- 第欧根尼已是当前主说时，旧主说仍需完整运行条件识别，等于保留第二套隐形主说；
- 每种旧效果要有独立的“将要结算”中断点，永久取得、商店交易和一次性效果仍无通用入口；
- 战斗中模态选择、手柄焦点、多人同步、接受后的即时奖励与战后正式恢复都要新增流程；
- 对当前无名环仍无可拦截的持续结算，无法解决真正上游。

因此不把触发弹窗当低成本修补，也不先审接口或做原型。

