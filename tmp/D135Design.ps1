# 第欧根尼放下主说载体

## D135候选性质

本页是人物设计候选，不是批准能力、技术方案或历史结论。它针对D134的硬条件，只审一个在既定路径中确定存在的对象：**当前主说带来的局内机械赐福**。玩家保留已经发生的对话、理由和路线历史，只暂时停止机械效果；不能把“放下赐福”写成拒绝一切教导、关系或帮助。

候选问题是：**当一份确定有用的哲学赐福可以取回时，我是否愿意先不用它生活；事实表明需要时，能否公开承认并改回？** 这是游戏转译，不冒称第欧根尼原话。研究依据与边界见[[03研究与资料/西方哲学史/24第欧根尼自足与操练]]。

## 正式节点、操作与制作成本

### 出现时点

只在既定第二幕Question中出现第欧根尼邀请。进入此节点前必须确实有且仅有一个当前主说机械效果；调试局、效果缺失、效果无法安全暂停或来源不明时不显示采用选项，不临时发一件物品凑条件。

采用页给两个可理解的结果：

1. 保留当前主说并离开：不进入第欧根尼实践，不改变路线历史或机械效果。
2. 放下当前赐福：保存前一主说的公开身份和可恢复状态，使其机械效果失效；第欧根尼成为唯一当前主说，提供实践状态而不提供攻击、格挡、抽牌、能量或资源补偿。

之后只在非战斗、非奖励结算、无其他模态窗口的安全时点开放状态入口。入口显示前一赐福名称、已在没有它的情况下进入过哪些合格普通战斗，以及“继续”与“取回并结束实践”。不在每场战斗前强弹窗；玩家能取回而没有取回，进入下一场合格战斗时才记录一次继续事实。

第三幕沿既定路线处理：仍处于实践时，可选择停留为合法终点，或通过公开的犬儒传统/克拉特斯中介转向季蒂昂芝诺；取回旧赐福后，不把已结束的实践当成芝诺门票。转向芝诺会正常替换当前主说，不让旧赐福与新赐福同时生效。

### 界面

- 第二幕：复用标准Question事件页及选项/确认页，必须在确认前列明将暂停的准确机械效果。
- 幕间实践：复用当前主说的状态入口或既有路线详情，不新增战斗按钮、手柄秘密操作或地图常驻弹窗。
- 第三幕：复用既定Question/Switch或停留结点；事实记录只显示做过的战斗和是否取回，不显示“自足分”“勇敢分”。
- 若现有主说状态没有玩家可发现的详情入口，新增完整浮层会提高制作和控制器焦点成本；在入口未证实前不能把一句悬停提示算正式可用。

### 素材与动画

上限暂为一张第欧根尼静态人物/事件图和一枚实践状态图标；来源、风格一致性和小尺寸可读性均未解决。前一赐福继续使用自己的既有图标并明确显示“已暂停”，不复制整套美术。不新增桶屋、街市、群众、统治者、丢弃动作或战斗动画。若正式表达必须依靠这些场景，候选退回。

## 完整决策循环

1. 玩家在第欧根尼面前看到自己当前真实拥有的主说效果，不由作者虚构一种依赖。
2. 玩家保留它并离开，或明确放下其机械收益；采用后没有暗中补偿。
3. 玩家用原有牌组、药水、遗物和正常游戏规则进入普通战斗；这些帮助不被禁止，也不因使用而判失败。
4. 每个安全局外时点，玩家可以继续实践，或承认当前仍需要原赐福并取回。取回立刻结束第欧根尼主说，不罚款、不抹去已发生事实。
5. 若继续，下一场合格普通战斗在效果确实未生效时留下事实；无战斗机会、调试生成或无效战斗不计。
6. 第三幕只根据玩家仍处于实践、已经取回或从未采用显示相应事实和合法后继。玩家自己选择停留或经中介转向芝诺，程序不从次数推断动机或德性。

这个循环的替代方式不是新卡或新数值，而是玩家原本已有的牌组与操作能力。它检验的是对“哲学路线赠予的额外机械优势”的依赖，不宣称已经检验财富、社会地位或所有外物。

## 取舍、收益与代价

代价是明确且持续的：前一主说的局内收益停止，普通战斗可能更难。取回的代价不是金币、生命或羞辱，而是结束本次第欧根尼实践并回到前一主说；之前经历仍可在历史里陈述，但不继续积累实践事实。

候选不提供数值收益。停留结局和芝诺选项是路线结果，不是“吃苦兑换强力奖励”。这也暴露最大可玩性风险：玩家可能只把它看成一条少拿奖励的困难模式，强构筑无感、弱构筑直接取回，中间缺少有趣的主动操作。若纸面与体验都找不到除自设难度以外的乐趣，候选应否决，不能靠追加力量、抽牌或稀有奖励救活。

## 表达机会和公开边界

采用选择由第欧根尼在正式事件中见证，因此不是纯私人日志。局中状态只记录机械事实，不声称敌人或路人理解玩家。第三幕若转向芝诺，必须公开犬儒传统与克拉特斯中介，并让玩家陈述“继续不用”“事实表明需要帮助”或“愿意接受另一种训练”的实际情况；后继选择会改变当前主说，具有真实关系后果。

这仍只提供较弱的公开表达：第欧根尼见证选择、后继人物接收陈述，不等于面对政治权势的parrhēsia。候选若保留，只能称德性与幸福路线中的公开自足实践，不能冒称完整再现犬儒政治直言；反习俗转入历史与权力仍是后设投影。

## 失败、恢复与保存要求

- 取回只能发生在安全局外时点；战斗中发现困难时仍按正常规则处理，不能即时恢复旧效果抹掉风险。
- 玩家可在下一场战斗前取回，记录为“采用后修订、未进入合格战斗”，不叫作弊或失败。
- 战败按正常游戏处理，不提供倒带。无合格战斗机会记“无机会”，不算完成或失败。
- 暂停必须覆盖效果的所有持续部分；恢复必须还原准确状态，不重复触发取得奖励、首次进入、计数或永久牌组修改。
- 保存/读取需原子保留前一主说身份、暂停状态、已记录事实和是否结束。任一部分不能安全往返，候选不能接生产。

